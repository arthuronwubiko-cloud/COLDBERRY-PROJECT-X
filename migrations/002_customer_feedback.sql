-- Romeo's Pizza: customer feedback (Supabase)
-- Creates customer_feedback table and policies for anonymous feedback submission
-- Run in the Supabase SQL editor. Safe to re-run.
-- Neon databases (DATABASE_URL) are upgraded automatically by ensureNeonSchema in api/db.js.

create table if not exists public.customer_feedback (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz default now(),
  rating        int not null check (rating >= 1 and rating <= 5),
  customer_name text,
  order_pin     text,
  tags          text,
  comments      text,
  source        text default 'web_bubble'
);

-- Enable RLS
alter table public.customer_feedback enable row level security;

-- Allow anonymous inserts (anyone can submit feedback)
create policy "Allow anonymous feedback insert"
  on public.customer_feedback
  for insert
  to anon, authenticated, service_role
  with check (true);

-- Allow reading feedback
create policy "Allow feedback select"
  on public.customer_feedback
  for select
  to anon, authenticated, service_role
  using (true);
